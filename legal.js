export function openLegal(kind = 'terms') {
  if (document.querySelector('.overlay.lgl')) return;
  const el = document.createElement('div'); el.className = 'overlay lgl';
  const tab = (k, t) => `<button type="button" class="fchip ${k === kind ? 'on' : ''}" data-k="${k}">${t}</button>`;
  const draw = k => {
    const [title, secs] = DOCS[k];
    el.querySelector('.lg-body').innerHTML = `<div class="lg-note">${ic('info', 16)} مسودة تحتاج مراجعة واعتماد المالك أو مستشار قانوني قبل النشر النهائي.</div>
      <h2>${esc(title)}</h2><p class="lg-meta">الإصدار ${LEGAL_VERSION} · آخر تحديث ${LEGAL_DATE}</p>
      ${secs.map(([h, t]) => `<h3>${esc(h)}</h3><p>${esc(t)}</p>`).join('')}
      <div class="lg-contact"><b>للدعم والاستفسارات</b><a class="btn light" href="tel:${SUPPORT}">${ic('phone', 18)} ${SUPPORT}</a></div>`;
    el.querySelectorAll('[data-k]').forEach(b => b.classList.toggle('on', b.dataset.k === k));
    el.querySelector('.lg-body').scrollTop = 0;
  };
  el.innerHTML = `<header class="top"><button class="icon-btn" data-x aria-label="رجوع">${ic('back', 22)}</button><div class="ttl">الشروط والخصوصية</div><span style="width:40px"></span></header>
    <div class="filt lg-tabs">${tab('terms', 'الشروط والأحكام')}${tab('privacy', 'سياسة الخصوصية')}${tab('aup', 'الاستخدام المقبول')}</div><div class="lg-body"></div>`;
  document.body.appendChild(el);
  el.addEventListener('click', e => { if (e.target.closest('[data-x]')) el.remove(); const k = e.target.closest('[data-k]'); if (k) draw(k.dataset.k); });
  draw(kind);
}
window.openLegal = openLegal;
